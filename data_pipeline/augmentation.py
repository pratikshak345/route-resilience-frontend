def get_train_transform():
    """
    Albumentations pipeline for training data.
    Includes robust occlusion-simulating augmentations as requested.
    """
    return A.Compose([
        A.HorizontalFlip(p=0.5),
        A.VerticalFlip(p=0.5),
        A.RandomRotate90(p=0.5),
        A.Transpose(p=0.5),
        
        # Occlusion simulations
        A.RandomShadow(p=0.3), # Tree/building shadows
        A.CoarseDropout(max_holes=8, max_height=32, max_width=32, min_holes=2, min_height=16, min_width=16, p=0.3), # Cloud patches
        
        # Illumination/Seasonal changes
        A.RandomBrightnessContrast(p=0.5),
        A.RandomGamma(p=0.3),
        
        # Noise robustness
        A.GaussNoise(var_limit=(10.0, 50.0), p=0.3),
        A.GaussianBlur(blur_limit=(3, 7), p=0.3),
        
        # Normalization for ImageNet weights
        A.Normalize(
            mean=[0.485, 0.456, 0.406],
            std=[0.229, 0.224, 0.225],
        ),
        ToTensorV2()
    ])

def get_val_transform():
    """
    Standard transforms for validation/testing (only normalization and tensor conversion).
    """
    return A.Compose([
        A.Normalize(
            mean=[0.485, 0.456, 0.406],
            std=[0.229, 0.224, 0.225],
        ),
        ToTensorV2()
    ])

class RoadDataset(Dataset):
    """
    PyTorch Dataset for road segmentation.
    Loads image-mask pairs using the manifest CSV generated by tiling.py.
    """
    def __init__(self, manifest_path, split="train", transform=None):
        self.manifest = pd.read_csv(manifest_path)
        self.manifest = self.manifest[self.manifest['split'] == split].reset_index(drop=True)
        self.transform = transform
        
    def __len__(self):
        return len(self.manifest)
        
    def __getitem__(self, idx):
        img_path = self.manifest.loc[idx, 'tile_path']
        mask_path = self.manifest.loc[idx, 'mask_path']
        
        # Handle both TIFF and PNG formats
        if img_path.endswith('.tif') or img_path.endswith('.tiff'):
            import rasterio
            with rasterio.open(img_path) as src:
                # Read RGB and transpose to HWC for Albumentations
                image = src.read([1, 2, 3]).transpose(1, 2, 0)
        else:
            image = cv2.imread(img_path)
            image = cv2.cvtColor(image, cv2.COLOR_BGR2RGB)
            
        if mask_path.endswith('.tif') or mask_path.endswith('.tiff'):
            import rasterio
            with rasterio.open(mask_path) as src:
                mask = src.read(1)
        else:
            mask = cv2.imread(mask_path, cv2.IMREAD_GRAYSCALE)
            
        # Ensure mask is binary (0 and 1)
        mask = (mask > 0).astype(np.float32)
        
        if self.transform:
            augmented = self.transform(image=image, mask=mask)
            image = augmented['image']
            mask = augmented['mask']
            
        # Add channel dimension to mask (1, H, W)
        if isinstance(mask, np.ndarray):
            mask = torch.from_numpy(mask).unsqueeze(0)
        else:
            mask = mask.unsqueeze(0)
            
        return image, mask
